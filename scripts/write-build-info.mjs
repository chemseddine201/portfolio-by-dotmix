/**
 * Runs before `mix dev`, `mix build` and `mix check`. Writes the facts the site prints but must never
 * hand-type (DESIGN.md §5.2), from their single sources:
 * - src/data/build-info.ts: build date, installed @dotmix/runtime version, site URL (package.json "homepage"),
 *   public contact values from .env (git-ignored, like .env);
 * - public/robots.txt and public/sitemap.xml for that site URL.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectDirectory = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const projectManifest = JSON.parse(fs.readFileSync(path.join(projectDirectory, "package.json"), "utf-8"));
const siteUrl = String(projectManifest.homepage ?? "").replace(/\/+$/, "");
if (!/^https?:\/\//.test(siteUrl)) {
  throw new Error('package.json "homepage" must be the site URL, e.g. "https://example.com".');
}

/** Version of the @dotmix/runtime this project resolves (the installed one, not the declared range). */
function readInstalledRuntimeVersion() {
  let directory = path.dirname(fileURLToPath(import.meta.resolve("@dotmix/runtime")));
  for (;;) {
    const manifestPath = path.join(directory, "package.json");
    if (fs.existsSync(manifestPath)) {
      const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf-8"));
      if (manifest.name === "@dotmix/runtime") return manifest.version;
    }
    const parentDirectory = path.dirname(directory);
    if (parentDirectory === directory) throw new Error("Cannot find the installed @dotmix/runtime package.json.");
    directory = parentDirectory;
  }
}

/** Public contact values printed on the page. Read from the environment, then from .env (KEY=value lines). */
const CONTACT_KEYS = {
  email: "PORTFOLIO_EMAIL",
  whatsappNumber: "PORTFOLIO_WHATSAPP",
  facebookUrl: "PORTFOLIO_FACEBOOK",
  calendarUrl: "PORTFOLIO_CALENDAR_URL",
};

function readDotEnv(filePath) {
  const values = {};
  if (!fs.existsSync(filePath)) return values;
  for (const rawLine of fs.readFileSync(filePath, "utf-8").split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line === "" || line.startsWith("#")) continue;
    const separatorIndex = line.indexOf("=");
    if (separatorIndex < 1) continue;
    let value = line.slice(separatorIndex + 1).trim();
    const quote = value[0];
    if ((quote === '"' || quote === "'") && value.length >= 2 && value.endsWith(quote)) value = value.slice(1, -1);
    values[line.slice(0, separatorIndex).trim()] = value;
  }
  return values;
}

function readContact() {
  const dotEnvValues = readDotEnv(path.join(projectDirectory, ".env"));
  const contact = {};
  for (const [field, key] of Object.entries(CONTACT_KEYS)) {
    contact[field] = process.env[key] ?? dotEnvValues[key] ?? "";
  }
  return contact;
}

function escapeXml(text) {
  return text.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
}

function writeIfChanged(filePath, contents) {
  if (fs.existsSync(filePath) && fs.readFileSync(filePath, "utf-8") === contents) return;
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents, "utf-8");
}

const buildInfo = {
  builtAt: new Date().toISOString().slice(0, 10),
  dotmixVersion: readInstalledRuntimeVersion(),
  siteUrl,
  contact: readContact(),
};

writeIfChanged(
  path.join(projectDirectory, "src", "data", "build-info.ts"),
  [
    "// Generated by scripts/write-build-info.mjs before every dev, build and check. Do not edit.",
    "export interface BuildInfo {",
    "  /** Build date, YYYY-MM-DD. */",
    "  readonly builtAt: string;",
    "  /** Installed @dotmix/runtime version. */",
    "  readonly dotmixVersion: string;",
    '  /** Site origin from package.json "homepage", without a trailing slash. */',
    "  readonly siteUrl: string;",
    "  /** Public contact values from .env (PORTFOLIO_*); \"\" hides the item. */",
    "  readonly contact: {",
    "    readonly email: string;",
    "    readonly whatsappNumber: string;",
    "    readonly facebookUrl: string;",
    "    readonly calendarUrl: string;",
    "  };",
    "}",
    "",
    `export const buildInfo: BuildInfo = ${JSON.stringify(buildInfo, null, 2)};`,
    "",
  ].join("\n")
);
writeIfChanged(path.join(projectDirectory, "public", "robots.txt"), `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`);
writeIfChanged(
  path.join(projectDirectory, "public", "sitemap.xml"),
  [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    "  <url>",
    `    <loc>${escapeXml(`${siteUrl}/`)}</loc>`,
    `    <lastmod>${buildInfo.builtAt}</lastmod>`,
    "  </url>",
    "</urlset>",
    "",
  ].join("\n")
);
